def terms_in(text, secret=False):
    """증강 문구에 등장하는 용어를 찾는다. 긴 용어부터 봐서 부분일치를 피한다."""
    found = []
    for t in TERM_TAG_ORDER:
        if t == "비밀":
            if secret:
                found.append(t)
            continue
        if t in text:
            found.append(t)
    return found


